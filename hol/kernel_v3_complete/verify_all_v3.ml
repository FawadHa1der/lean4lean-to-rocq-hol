(* Load-and-prove driver for every hol/*.ml module of kernel_v3_complete.
   Run through verify_all_v3.sh (which compiles the Wire/Replay frontend and
   sets LEAN4LEAN_V3_FRONTEND_DIR / LEAN4LEAN_FIXTURE_TMPDIR), from this
   directory, by feeding this file to hol.sh on stdin.
   Each module is loaded with use_file_raise_failure := true so a failing
   module is NOT recorded in loaded_files and its status is reported as
   V3_MODULE_FAIL. Module order = needs-closure DFS order (README roots first,
   then the remaining modules alphabetically). No axioms, no unsound escapes. *)

(* Prerequisites declared by full_input610 / source_decoder641 / 643 / 649:
   the genuine Wire (frontend/wire.ml) and Replay (frontend/replay.ml)
   modules plus Zarith and Yojson. Zarith is already linked into ocaml-hol;
   only its interface directory has to be made visible. *)
let v3_frontend_dir =
  try Sys.getenv "LEAN4LEAN_V3_FRONTEND_DIR"
  with Not_found -> failwith "LEAN4LEAN_V3_FRONTEND_DIR is not set";;
Topdirs.dir_directory (Findlib.package_directory "zarith");;
Topfind.load_deeply ["yojson"];;
Topdirs.dir_directory v3_frontend_dir;;
Topdirs.dir_load Format.std_formatter (Filename.concat v3_frontend_dir "wire.cmo");;
Topdirs.dir_load Format.std_formatter (Filename.concat v3_frontend_dir "replay.cmo");;

use_file_raise_failure := true;;
let v3_ok = ref ([]:string list);;
let v3_fail = ref ([]:(string*string) list);;
let v3_try f =
  let t0 = Sys.time () in
  try
    needs f;
    v3_ok := f :: !v3_ok;
    Printf.printf "\nV3_MODULE_OK %s cpu=%.1fs\n%!" f (Sys.time () -. t0)
  with e ->
    let m = Printexc.to_string e in
    v3_fail := (f,m) :: !v3_fail;
    Printf.printf "\nV3_MODULE_FAIL %s : %s\n%!" f m;;

