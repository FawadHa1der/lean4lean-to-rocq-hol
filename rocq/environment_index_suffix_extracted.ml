    (** val flatten_e : 'a1 enumeration -> (key, 'a1) prod list **)

    let rec flatten_e = function
    | End -> Nil
    | More (x, e0, t0, r) ->
      Cons ((Pair (x, e0)), (app (elements t0) (flatten_e r)))
   end
 end

