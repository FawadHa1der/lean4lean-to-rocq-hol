From Coq Require Import List Bool Arith PeanoNat Lia.
From LeanPort Require Import Syntax.
Import ListNotations.

Fixpoint level_eval (rho : name -> nat) (u : level) : nat :=
  match u with
  | LZero => 0
  | LSucc v => S (level_eval rho v)
  | LMax a b => Nat.max (level_eval rho a) (level_eval rho b)
  | LIMax a b => match level_eval rho b with
                | 0 => 0 | S n => Nat.max (level_eval rho a) (S n) end
  | LParam n => rho n
  | LMVar _ => 0 (* Evaluation lemmas concern meta-free universes only. *)
  end.

Inductive sublevel :=
| SubConst : list name -> nat -> sublevel
| SubVar : list name -> name -> nat -> sublevel.

Definition guard_insert (n : name) (ns : list name) : list name :=
  if name_mem n ns then ns else n :: ns.
Definition const_atom (path : list name) (k : nat) : list sublevel :=
  match k with 0 => [] | S _ => [SubConst path k] end.
Definition combine_levels (a b : result (list sublevel)) : result (list sublevel) :=
  xs <- a ;; ys <- b ;; Accept (xs ++ ys).

(* Each SubVar carries its own variable in its guard. Unlike upstream's
   grouped map, redundant atoms need not be minimized: domination is per atom.
   Keeping guarded constants of height one is semantically harmless. *)
Fixpoint normalize_aux (fuel : nat) (u : level) (path : list name) (k : nat)
    : result (list sublevel) :=
  match fuel with
  | 0 => Decline OutOfFuel
  | S fuel =>
    match u with
    | LZero => Accept (const_atom path k)
    | LSucc v => normalize_aux fuel v path (S k)
    | LMax a b => combine_levels (normalize_aux fuel a path k)
                                 (normalize_aux fuel b path k)
    | LParam n => Accept (const_atom path k ++ [SubVar (guard_insert n path) n k])
    | LMVar _ => Reject MetaVariable
    | LIMax a b =>
      match b with
      | LZero => Accept (const_atom path k)
      | LSucc v => combine_levels (normalize_aux fuel a path k)
                                   (normalize_aux fuel v path (S k))
      | LMax v w => combine_levels (normalize_aux fuel (LIMax a v) path k)
                                    (normalize_aux fuel (LIMax a w) path k)
      | LIMax v w => combine_levels (normalize_aux fuel (LIMax a w) path k)
                                     (normalize_aux fuel (LIMax v w) path k)
      | LParam n =>
          let path' := guard_insert n path in
          xs <- normalize_aux fuel a path' k ;;
          Accept (const_atom path k ++ SubVar path' n k :: xs)
      | LMVar _ => Reject MetaVariable
      end
    end
  end.

Definition normalize_level (fuel : nat) (u : level) : result (list sublevel) :=
  if level_has_meta u then Reject MetaVariable else normalize_aux fuel u [] 0.

Definition guard_subset (xs ys : list name) : bool :=
  forallb (fun x => name_mem x ys) xs.

(* Theorem 39's sublevel domination, including the constant <= offset+1
   case. The extra membership test makes this valid for arbitrary SubVar data,
   not only the well-formed atoms generated by normalize_aux. *)
Definition sublevel_le (a b : sublevel) : bool :=
  match a, b with
  | SubConst p k, SubConst q j => guard_subset q p && (k <=? j)
  | SubConst p k, SubVar q n j =>
      guard_subset q p && name_mem n q && (k <=? S j)
  | SubVar p n k, SubVar q m j =>
      guard_subset q p && name_eqb n m && (k <=? j)
  | _, _ => false
  end.

Definition sublevels_le (xs ys : list sublevel) : bool :=
  forallb (fun x => existsb (sublevel_le x) ys) xs.

Definition level_le (fuel : nat) (u v : level) : result bool :=
  xs <- normalize_level fuel u ;; ys <- normalize_level fuel v ;;
  Accept (sublevels_le xs ys).

Definition level_equiv (fuel : nat) (u v : level) : result bool :=
  xs <- normalize_level fuel u ;; ys <- normalize_level fuel v ;;
  Accept (sublevels_le xs ys && sublevels_le ys xs).

Fixpoint levels_equiv (fuel : nat) (us vs : list level) : result bool :=
  match us, vs with
  | [], [] => Accept true
  | u :: us, v :: vs =>
      b <- level_equiv fuel u v ;;
      if b then levels_equiv fuel us vs else Accept false
  | _, _ => Accept false
  end.

Definition guard_holds (rho : name -> nat) (ns : list name) : bool :=
  forallb (fun n => negb (Nat.eqb (rho n) 0)) ns.
Definition sublevel_eval (rho : name -> nat) (s : sublevel) : nat :=
  match s with
  | SubConst p k => if guard_holds rho p then k else 0
  | SubVar p n k => if guard_holds rho p then rho n + k else 0
  end.

Fixpoint sublevels_eval (rho : name -> nat) (ss : list sublevel) : nat :=
  match ss with
  | [] => 0
  | s :: ss => Nat.max (sublevel_eval rho s) (sublevels_eval rho ss)
  end.

Lemma name_mem_spec n ns : name_mem n ns = true <-> In n ns.
Proof.
  unfold name_mem. rewrite existsb_exists. split.
  - intros [m [Hm Heq]]. apply name_eqb_eq in Heq. subst. assumption.
  - intros H. exists n. split; [assumption | apply name_eqb_refl].
Qed.

Lemma guard_subset_sound rho xs ys :
  guard_subset xs ys = true -> guard_holds rho ys = true ->
  guard_holds rho xs = true.
Proof.
  unfold guard_subset, guard_holds. rewrite !forallb_forall.
  intros Hsub Hguard n Hn. apply Hguard.
  apply name_mem_spec. apply Hsub. assumption.
Qed.

Lemma guard_member_positive rho ns n :
  guard_holds rho ns = true -> name_mem n ns = true -> 0 < rho n.
Proof.
  unfold guard_holds. rewrite forallb_forall.
  intros Hguard Hmem. apply name_mem_spec in Hmem.
  specialize (Hguard n Hmem). apply negb_true_iff in Hguard.
  apply Nat.eqb_neq in Hguard. lia.
Qed.

Theorem sublevel_le_sound rho a b :
  sublevel_le a b = true -> sublevel_eval rho a <= sublevel_eval rho b.
Proof.
  destruct a as [p k | p n k], b as [q j | q m j]; simpl; try discriminate.
  - intros H. apply andb_true_iff in H as [Hs Hk]. apply Nat.leb_le in Hk.
    destruct (guard_holds rho p) eqn:Hp; [|lia].
    rewrite (guard_subset_sound rho q p Hs Hp). assumption.
  - intros H. apply andb_true_iff in H as [H Hk].
    apply andb_true_iff in H as [Hs Hm]. apply Nat.leb_le in Hk.
    destruct (guard_holds rho p) eqn:Hp; [|lia].
    pose proof (guard_subset_sound rho q p Hs Hp) as Hq. rewrite Hq.
    pose proof (guard_member_positive rho q m Hq Hm). lia.
  - intros H. apply andb_true_iff in H as [H Hk].
    apply andb_true_iff in H as [Hs Hnm]. apply Nat.leb_le in Hk.
    apply name_eqb_eq in Hnm. subst m.
    destruct (guard_holds rho p) eqn:Hp; [|lia].
    rewrite (guard_subset_sound rho q p Hs Hp). lia.
Qed.

Lemma sublevel_member_bound rho b bs :
  In b bs -> sublevel_eval rho b <= sublevels_eval rho bs.
Proof.
  induction bs as [|a bs IH]; simpl; [tauto|].
  intros [<- | Hin]; [apply Nat.le_max_l|].
  eapply Nat.le_trans; [apply IH; exact Hin | apply Nat.le_max_r].
Qed.

Theorem sublevels_le_sound rho xs ys :
  sublevels_le xs ys = true -> sublevels_eval rho xs <= sublevels_eval rho ys.
Proof.
  induction xs as [|x xs IH]; simpl; [intros; apply Nat.le_0_l|].
  unfold sublevels_le in *. simpl. intros H.
  apply andb_true_iff in H as [Hx Hxs]. apply Nat.max_lub.
  - apply existsb_exists in Hx as [y [Hy Hle]].
    eapply Nat.le_trans; [apply sublevel_le_sound; exact Hle|].
    apply sublevel_member_bound. exact Hy.
  - apply IH. exact Hxs.
Qed.

Lemma eval_imax_zero rho u : level_eval rho (LIMax u LZero) = 0.
Proof. reflexivity. Qed.

Lemma eval_imax_succ rho u v :
  level_eval rho (LIMax u (LSucc v)) = level_eval rho (LMax u (LSucc v)).
Proof. reflexivity. Qed.

Lemma normalize_no_fuel u path k : normalize_aux 0 u path k = Decline OutOfFuel.
Proof. reflexivity. Qed.
